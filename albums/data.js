/*
 * Photo entries carry their pixel size so the pages can reserve each box up
 * front (see albums/measure-images.js). These read an entry either way, so a
 * hand-added plain string still renders — it just falls back to a default box.
 */
window.albumPhoto = function (entry) {
  if (typeof entry === "string") {
    return { src: entry, w: 0, h: 0 };
  }
  if (!entry || !entry.src) {
    return { src: "", w: 0, h: 0 };
  }
  return { src: entry.src, w: Number(entry.w) || 0, h: Number(entry.h) || 0 };
};

window.albumPhotoSrc = function (entry) {
  return window.albumPhoto(entry).src;
};
